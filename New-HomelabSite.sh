#!/usr/bin/env bash
# Convert a flat homelab-deploy install into a site instance (in place).
# Same behaviour as New-HomelabSite.ps1.
#
# Usage:
#   ./New-HomelabSite.sh --site-repo https://github.com/ORG/REPO.git --push --start
set -euo pipefail

SITE_REPO=""
BRANCH="homelab"
TARGET_DIR=""
UPSTREAM_URL="https://github.com/opendevtools-org/homelab-deploy.git"
PORTS="lan"
SKIP_GIT=0
PUSH=0
START=0
SKIP_COMMIT=0

usage() {
  sed -n '2,8p' "$0" | sed 's/^# //'
  echo "Options: --site-repo URL  --branch NAME  --target-dir PATH  --upstream-url URL"
  echo "         --ports lan|local  --skip-git  --push  --start  --skip-commit"
  exit "${1:-0}"
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --site-repo) SITE_REPO="$2"; shift 2 ;;
    --branch) BRANCH="$2"; shift 2 ;;
    --target-dir) TARGET_DIR="$2"; shift 2 ;;
    --upstream-url) UPSTREAM_URL="$2"; shift 2 ;;
    --ports) PORTS="$2"; shift 2 ;;
    --skip-git) SKIP_GIT=1; shift ;;
    --push) PUSH=1; shift ;;
    --start) START=1; shift ;;
    --skip-commit) SKIP_COMMIT=1; shift ;;
    -h|--help) usage 0 ;;
    *) echo "Unknown option: $1" >&2; usage 1 ;;
  esac
done

need() { command -v "$1" >/dev/null 2>&1 || { echo "Required command not found: $1" >&2; exit 1; }; }
need git
[[ "$START" -eq 1 ]] && need docker

GITIGNORE_PLACEHOLDER='# Site-specific ignore rules go here. Product rules are in .gitignore.upstream.'

gitignore_extras() {
  local existing="$1" product="$2" line
  while IFS= read -r line || [[ -n "$line" ]]; do
    line="${line%$'\r'}"
    [[ -z "$line" ]] && continue
    [[ "$line" == "# Generated"* ]] && continue
    [[ "$line" == "# Site-specific"* ]] && continue
    [[ "$line" == "# Site extras"* ]] && continue
    [[ "$line" == "# Product rules:"* ]] && continue
    grep -qxF "$line" <(tr -d '\r' < "$product") 2>/dev/null && continue
    printf '%s\n' "$line"
  done < "$existing"
}

write_layered_gitignore() {
  local product_src="$1" dest_root="$2" bak_dir="${3:-}"
  local snapshot="$dest_root/.gitignore.upstream"
  local custom="$dest_root/.gitignore.custom"
  local effective="$dest_root/.gitignore"
  if [[ -f "$product_src" ]]; then
    cp -a "$product_src" "$snapshot"
  fi
  if [[ ! -f "$custom" ]]; then
    if [[ -n "$bak_dir" && -f "$bak_dir/.gitignore.custom" ]]; then
      cp -a "$bak_dir/.gitignore.custom" "$custom"
    elif [[ -n "$bak_dir" && -f "$bak_dir/.gitignore" && -f "$product_src" ]]; then
      extras="$(gitignore_extras "$bak_dir/.gitignore" "$product_src" || true)"
      if [[ -n "${extras:-}" ]]; then
        printf '%s\n' "$extras" >"$custom"
      else
        printf '%s\n' "$GITIGNORE_PLACEHOLDER" >"$custom"
      fi
    else
      printf '%s\n' "$GITIGNORE_PLACEHOLDER" >"$custom"
    fi
  fi
  if [[ -f "$product_src" ]]; then
    {
      printf '%s\n' \
        '# Generated. Do not edit this file.' \
        '# Product rules: .gitignore.upstream (refreshed by Update-HomelabUpstream).' \
        '# Site extras: .gitignore.custom'
      cat "$product_src"
      printf '\n%s\n' '# Site extras from .gitignore.custom.'
      cat "$custom"
    } >"$effective"
  elif [[ -f "$custom" ]]; then
    cp -a "$custom" "$effective"
  else
    printf '%s\n' "$GITIGNORE_PLACEHOLDER" >"$effective"
  fi
}

env_val() {
  local key="$1" file="$2"
  grep -E "^[[:space:]]*${key}=" "$file" 2>/dev/null | tail -n1 | cut -d= -f2- | tr -d '\r' | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' -e 's/^["'\'']//' -e 's/["'\'']$//'
}

https_overlay_enabled() {
