  local envf="$root/.env"
  local overlay="$root/docker-compose.https.yml"
  [[ -f "$overlay" && -f "$envf" ]] || return 1
  local hub pkm
  hub="$(env_val HUB_HOSTNAME "$envf")"
  pkm="$(env_val PKM_HOSTNAME "$envf")"
  [[ -n "$hub" && -n "$pkm" ]]
}

